<?php

namespace App\Http\Requests\Learn;

use Carbon\CarbonInterface;
use Closure;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Support\Facades\Date;

/**
 * One practice answer (PRAC-04, TEST-06, TIME-04; spec 0003 B.9).
 *
 * `answers` is keyed by item id and shaped per activity type: an option id,
 * a prompt→target map, an ordered id list, `{recording_media_id, duration_ms}`
 * or `{text}`. The shape is validated loosely here and judged by
 * ActivityScorer; a malformed item answer is simply wrong, never a 500.
 * Authorization is the LessonPolicy check in the controller.
 */
class AnswerActivityRequest extends FormRequest
{
    public function authorize(): bool
    {
        return $this->user() !== null;
    }

    /**
     * The longest text one item answer may hold. A written answer is sent
     * verbatim to the AI evaluator, so an unbounded one is unbounded spend
     * (WRITE-04, AIL-01; security audit 2026-11-08).
     */
    public const int MAX_TEXT_LENGTH = 5000;

    /** The largest whole answer payload, JSON encoded. */
    public const int MAX_PAYLOAD_LENGTH = 50000;

    /**
     * @return array<string, list<string|Closure>>
     */
    public function rules(): array
    {
        return [
            'answers' => ['required', 'array', 'max:200', function (string $attribute, mixed $value, Closure $fail): void {
                $json = json_encode($value);

                if ($json === false || strlen($json) > self::MAX_PAYLOAD_LENGTH) {
                    $fail(__('This answer is too long.'));
                }
            }],
            'answers.*' => ['nullable', function (string $attribute, mixed $value, Closure $fail): void {
                $text = is_array($value) ? ($value['text'] ?? null) : $value;

                if (is_string($text) && mb_strlen($text) > self::MAX_TEXT_LENGTH) {
                    $fail(__('Please keep your answer under :max characters.', ['max' => self::MAX_TEXT_LENGTH]));
                }
            }],
            // The hidden field the page sets when the activity opens, so
            // time taken is measured from when the learner saw it.
            'started_at' => ['nullable', 'date'],
            // One key per submission, generated by the page: a retried
            // request of the same submission finds its attempt instead of
            // writing a second one (PROG-04; client report 2026-11-05).
            'submission_key' => ['nullable', 'string', 'max:64', 'regex:/^[A-Za-z0-9_-]+$/'],
        ];
    }

    /**
     * @return array<array-key, mixed>
     */
    public function answers(): array
    {
        /** @var array<array-key, mixed> $answers */
        $answers = $this->validated('answers');

        return $answers;
    }

    public function submissionKey(): ?string
    {
        $key = $this->validated('submission_key');

        return is_string($key) && $key !== '' ? $key : null;
    }

    public function startedAt(): ?CarbonInterface
    {
        $raw = $this->validated('started_at');

        return is_string($raw) && $raw !== '' ? Date::parse($raw) : null;
    }
}
